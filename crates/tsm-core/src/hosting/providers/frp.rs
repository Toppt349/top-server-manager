//! FRP client (frpc) towards an frps server on a VPS the user owns.
//! The generated `frpc.toml` references the auth token through frp's
//! `{{ .Envs.FRP_AUTH_TOKEN }}` template, so the token never touches disk.
//! Status comes from the frpc admin API (`/api/status`, loopback only) and is
//! then verified by connecting to the remote port on the VPS.

use crate::error::{CoreError, CoreResult};
use crate::hosting::agent::{AgentCtx, AgentFindings, AgentSession, AgentSessions};
use crate::hosting::*;
use crate::model::*;
use crate::runtime::RuntimeId;
use async_trait::async_trait;
use std::collections::BTreeMap;
use std::sync::Arc;

pub struct FrpProvider {
    ctx: AgentCtx,
    sessions: AgentSessions,
}

fn toml_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub fn proxy_type(p: &Project) -> &'static str {
    match p.protocol {
        Protocol::Udp => "udp",
        Protocol::Http | Protocol::WebSocket if p.hosting.frp_custom_domain.as_deref().map(|d| !d.is_empty()).unwrap_or(false) => "http",
        _ => "tcp",
    }
}

pub fn proxy_name(p: &Project) -> String {
    format!("tsm-{}", crate::util::slug(&p.id))
}

/// Generate frpc.toml (TOML format, frp >= 0.52).
pub fn frpc_config(p: &Project, admin_port: u16, with_token: bool) -> String {
    let h = &p.hosting;
    let mut s = String::new();
    s.push_str("# Generated by TOP Server Manager – do not edit, regenerated on each connect\n");
    s.push_str(&format!("serverAddr = {}\nserverPort = {}\n", toml_str(&h.frp_server), h.frp_server_port));
    if with_token {
        s.push_str("auth.method = \"token\"\nauth.token = \"{{ .Envs.FRP_AUTH_TOKEN }}\"\n");
    }
    s.push_str("loginFailExit = false\n");
    s.push_str(&format!("webServer.addr = \"127.0.0.1\"\nwebServer.port = {admin_port}\n\n"));
    let ty = proxy_type(p);
    s.push_str(&format!("[[proxies]]\nname = {}\ntype = \"{ty}\"\nlocalIP = \"127.0.0.1\"\nlocalPort = {}\n", toml_str(&proxy_name(p)), p.port));
    if ty == "http" {
        s.push_str(&format!("customDomains = [{}]\n", toml_str(h.frp_custom_domain.as_deref().unwrap_or(""))));
    } else {
        s.push_str(&format!("remotePort = {}\n", h.frp_remote_port));
    }
    s
}

/// Installation guide/script for frps on the user's VPS. It is only shown to
/// the user; nothing is executed remotely by this application.
pub fn vps_install_script(bind_port: u16, remote_ports: &str) -> String {
    format!(
        r#"#!/usr/bin/env bash
# FRP server (frps) install script for a Linux VPS you own.
# Review before running. Run as root: sudo bash install-frps.sh
# TOP Server Manager never runs this script or changes your VPS for you.
set -euo pipefail
FRP_VERSION="$(curl -fsSL https://api.github.com/repos/fatedier/frp/releases/latest | grep -oP '"tag_name":\s*"v\K[^"]+')"
ARCH=amd64; [ "$(uname -m)" = "aarch64" ] && ARCH=arm64
cd /tmp
curl -fsSLO "https://github.com/fatedier/frp/releases/download/v${{FRP_VERSION}}/frp_${{FRP_VERSION}}_linux_${{ARCH}}.tar.gz"
tar xzf "frp_${{FRP_VERSION}}_linux_${{ARCH}}.tar.gz"
install -m 755 "frp_${{FRP_VERSION}}_linux_${{ARCH}}/frps" /usr/local/bin/frps
mkdir -p /etc/frp
TOKEN="$(head -c 24 /dev/urandom | base64 | tr -d '/+=')"
cat > /etc/frp/frps.toml <<EOF
bindPort = {bind_port}
auth.method = "token"
auth.token = "$TOKEN"
allowPorts = [{{ start = 20000, end = 30000 }}]
EOF
cat > /etc/systemd/system/frps.service <<'EOF'
[Unit]
Description=frp server
After=network-online.target
[Service]
ExecStart=/usr/local/bin/frps -c /etc/frp/frps.toml
Restart=on-failure
[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload && systemctl enable --now frps
echo "frps is running. Auth token (paste into TOP Server Manager): $TOKEN"
echo "Now open TCP {bind_port} and your game ports ({remote_ports}) in the VPS firewall yourself, e.g.:"
echo "  ufw allow {bind_port}/tcp && ufw allow 20000:30000/tcp && ufw allow 20000:30000/udp"
"#
    )
}

impl FrpProvider {
    pub fn new(ctx: AgentCtx) -> Self {
        FrpProvider { ctx, sessions: AgentSessions::default() }
    }

    fn parse_line(line: &str, f: &mut AgentFindings) {
        let l = line.to_ascii_lowercase();
        if l.contains("login to server success") {
            f.extra.push("logged-in".into());
            f.last_error = None;
        }
        if l.contains("token in login doesn't match") || l.contains("authorization failed") {
            f.last_error = Some("frps rejected the auth token.".into());
        } else if l.contains("port already used") || l.contains("port not allowed") {
            f.last_error = Some(format!("frps refused the remote port: {}", line.chars().take(200).collect::<String>()));
        } else if l.contains("connect to server error") || l.contains("i/o timeout") {
            f.last_error = Some(format!("cannot reach the frps server: {}", line.chars().take(200).collect::<String>()));
        }
    }

    async fn api_status(port: u16, name: &str) -> Option<(String, String)> {
        let c = crate::health::http_client(std::time::Duration::from_secs(3));
        let v: serde_json::Value = c.get(format!("http://127.0.0.1:{port}/api/status")).send().await.ok()?.json().await.ok()?;
        for (_, list) in v.as_object()? {
            for p in list.as_array()? {
                if p["name"].as_str() == Some(name) {
                    return Some((p["status"].as_str().unwrap_or("").to_string(), p["err"].as_str().unwrap_or("").to_string()));
                }
            }
        }
        None
    }

    async fn evaluate(&self, s: &AgentSession) -> HostingState {
        let t = &s.target;
        let f = s.findings();
        if !s.alive() {
            let mut st = t.base_state(HostingStatus::Disconnected);
            st.message = Some(f.last_error.unwrap_or_else(|| "frpc exited".into()));
            return st;
        }
        let h = &t.project.hosting;
        let ty = proxy_type(&t.project);
        let public = if ty == "http" {
            format!("http://{}", h.frp_custom_domain.clone().unwrap_or_default())
        } else {
            format!("{}:{}", h.frp_server, h.frp_remote_port)
        };
        let mut st = t.base_state(HostingStatus::Connecting);
        st.public_address = Some(public.clone());
        let api = match s.aux_port {
            Some(p) => Self::api_status(p, &proxy_name(&t.project)).await,
            None => None,
        };
        match api {
            Some((status, err)) if status == "running" => {
                let (ok, detail) = match ty {
                    "http" => verify_public_http(&public).await,
                    "udp" => (false, "UDP proxy running on frps; UDP reachability cannot be verified generically".into()),
                    _ => verify_public_tcp(&h.frp_server, h.frp_remote_port).await,
                };
                st.status = if ok {
                    HostingStatus::PublicOnline
                } else if ty == "udp" {
                    HostingStatus::Unverified
                } else {
                    HostingStatus::Connecting
                };
                let detail = if ty == "udp" && t.project.kind == ServerKind::MinecraftBedrock {
                    match crate::players::minecraft_bedrock_status(&h.frp_server, h.frp_remote_port, std::time::Duration::from_secs(5)).await {
                        Some(_) => {
                            st.status = HostingStatus::PublicOnline;
                            "Bedrock ping through the VPS answered".to_string()
                        }
                        None => detail,
                    }
                } else {
                    detail
                };
                st.verification = Some(format!("frpc proxy running; {detail}"));
                if !err.is_empty() {
                    st.message = Some(err);
                }
            }
            Some((status, err)) => st.message = Some(format!("frpc proxy status: {status} {err}")),
            None => st.message = Some(f.last_error.unwrap_or_else(|| "Connecting to frps…".into())),
        }
        st
    }
}

#[async_trait]
impl HostingProvider for FrpProvider {
    fn id(&self) -> ProviderId {
        ProviderId::Frp
    }
    async fn detect_capabilities(&self) -> DetectedCapabilities {
        match self.ctx.runtimes.resolve(RuntimeId::Frpc, None) {
            Ok(p) => DetectedCapabilities { installed: true, binary: Some(p.display().to_string()), authenticated: None, detail: "frpc installed".into() },
            Err(e) => DetectedCapabilities { installed: false, detail: e.to_string(), ..Default::default() },
        }
    }
    fn validate_configuration(&self, t: &HostingTarget) -> Vec<String> {
        let h = &t.project.hosting;
        let mut e = vec![];
        if h.frp_server.trim().is_empty() {
            e.push("Enter your VPS address (frps server).".into());
        } else if h.frp_server.parse::<std::net::IpAddr>().is_err() {
            if let Err(err) = crate::security::validate_hostname(&h.frp_server) {
                e.push(err.to_string());
            }
        }
        if h.frp_server_port == 0 {
            e.push("Enter the frps bind port (usually 7000).".into());
        }
        if proxy_type(&t.project) != "http" && h.frp_remote_port == 0 {
            e.push("Enter the remote port to open on the VPS.".into());
        }
        if let Some(d) = h.frp_custom_domain.as_deref().filter(|d| !d.is_empty()) {
            if let Err(err) = crate::security::validate_hostname(d) {
                e.push(err.to_string());
            }
        }
        e
    }
    async fn prepare(&self, _t: &HostingTarget) -> CoreResult<()> {
        if self.ctx.runtimes.resolve(RuntimeId::Frpc, None).is_err() {
            self.ctx.runtimes.install(RuntimeId::Frpc, None).await?;
        }
        Ok(())
    }
    async fn connect(&self, t: &HostingTarget) -> CoreResult<HostingState> {
        if let Some(old) = self.sessions.remove(&t.project.id) {
            self.ctx.kill(&t.project.id, &old).await;
        }
        let exe = self.ctx.runtimes.resolve(RuntimeId::Frpc, None)?;
        let admin = crate::ports::find_free_tcp(7400, &[t.project.port]).ok_or_else(|| CoreError::Other("no free admin port".into()))?;
        let cfg = self.ctx.generated_dir(&t.project.id).join("frpc.toml");
        std::fs::write(&cfg, frpc_config(&t.project, admin, t.token.is_some()))?;
        let mut env = BTreeMap::new();
        if let Some(tok) = &t.token {
            self.ctx.logs.redactor().add_secret(tok);
            env.insert("FRP_AUTH_TOKEN".into(), tok.clone());
        }
        let (proc, findings) = self.ctx.spawn(&t.project.id, exe, vec!["-c".into(), cfg.display().to_string()], env, Arc::new(Self::parse_line)).await?;
        let s = Arc::new(AgentSession { process: proc, target: t.clone(), findings, aux_port: Some(admin) });
        self.sessions.insert(&t.project.id, s.clone());
        for _ in 0..12 {
            tokio::time::sleep(std::time::Duration::from_millis(750)).await;
            let st = self.evaluate(&s).await;
            if st.status != HostingStatus::Connecting {
                return Ok(st);
            }
        }
        Ok(self.evaluate(&s).await)
    }
    async fn disconnect(&self, id: &str) -> CoreResult<()> {
        if let Some(s) = self.sessions.remove(id) {
            self.ctx.kill(id, &s).await;
        }
        Ok(())
    }
    async fn get_status(&self, id: &str) -> Option<HostingState> {
        let s = self.sessions.get(id)?;
        Some(self.evaluate(&s).await)
    }
    async fn health_check(&self, id: &str) -> Option<HostingState> {
        self.get_status(id).await
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn config_never_contains_token() {
        let mut p = Project { id: "mc-abc".into(), port: 25565, protocol: Protocol::Tcp, ..Default::default() };
        p.hosting.frp_server = "vps.example.com".into();
        p.hosting.frp_server_port = 7000;
        p.hosting.frp_remote_port = 25565;
        let c = frpc_config(&p, 7400, true);
        assert!(c.contains("{{ .Envs.FRP_AUTH_TOKEN }}"));
        assert!(c.contains("remotePort = 25565"));
        assert!(c.contains("webServer.addr = \"127.0.0.1\""));
        assert!(c.contains("type = \"tcp\""));
        p.protocol = Protocol::Udp;
        assert!(frpc_config(&p, 7400, true).contains("type = \"udp\""));
    }
}
