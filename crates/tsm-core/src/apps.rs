//! One-click apps: a fresh WordPress or Laravel site, ready to start.
//!
//! * WordPress: official zip from wordpress.org, verified against the SHA-1
//!   wordpress.org publishes for it (the only checksum it offers), database
//!   settings read from the environment the app injects – no password is
//!   written into wp-config.php.
//! * Laravel: `composer create-project laravel/laravel` with the app's PHP and
//!   Composer; uses Laravel's own SQLite database out of the box.

use crate::engine::{Engine, MissingRuntime};
use crate::error::{CoreError, CoreResult};
use crate::model::*;
use crate::runtime::RuntimeId;
use crate::tr;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::Duration;

pub const APPS_LOG: &str = "apps";

fn check_target(folder: &Path) -> CoreResult<()> {
    if !folder.is_absolute() {
        return Err(CoreError::InvalidConfig(tr!("เลือกโฟลเดอร์แบบเต็ม เช่น D:\\Sites\\myblog", "Choose a full folder path, e.g. D:\\Sites\\myblog")));
    }
    if folder.exists() && std::fs::read_dir(folder).map(|mut d| d.next().is_some()).unwrap_or(true) {
        return Err(CoreError::InvalidConfig(tr!(
            "โฟลเดอร์ {} มีไฟล์อยู่แล้ว — เลือกโฟลเดอร์ใหม่หรือโฟลเดอร์ว่าง (โปรแกรมจะไม่เขียนทับไฟล์ของคุณ)",
            "{} is not empty – choose a new or empty folder (your files are never overwritten)",
            folder.display()
        )));
    }
    Ok(())
}

fn wp_secret() -> String {
    use rand::Rng;
    const CHARS: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!#%&()*+,-./:;<=>?@[]^_{|}~";
    let mut rng = rand::thread_rng();
    (0..64).map(|_| CHARS[rng.gen_range(0..CHARS.len())] as char).collect()
}

/// wp-config.php that takes the database settings from the environment.
pub fn wp_config(db_name: &str) -> String {
    let keys = ["AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"];
    let mut s = String::from(
        "<?php\n// Generated by TOP Server Manager.\n// Database settings come from the app (environment variables), so no password is stored in this file.\n",
    );
    s.push_str(&format!("define( 'DB_NAME', getenv( 'DB_DATABASE' ) ?: '{db_name}' );\n"));
    s.push_str("define( 'DB_USER', getenv( 'DB_USERNAME' ) ?: 'root' );\n");
    s.push_str("define( 'DB_PASSWORD', getenv( 'DB_PASSWORD' ) ?: '' );\n");
    s.push_str("define( 'DB_HOST', ( getenv( 'DB_HOST' ) ?: '127.0.0.1' ) . ':' . ( getenv( 'DB_PORT' ) ?: '3306' ) );\n");
    s.push_str("define( 'DB_CHARSET', 'utf8mb4' );\ndefine( 'DB_COLLATE', '' );\n\n");
    for k in keys {
        s.push_str(&format!("define( '{k}', '{}' );\n", wp_secret()));
    }
    s.push_str("\n$table_prefix = 'wp_';\n\ndefine( 'WP_DEBUG', false );\n// Behind a .test HTTPS proxy WordPress must know the page is HTTPS.\nif ( isset( $_SERVER['HTTP_X_FORWARDED_PROTO'] ) && 'https' === $_SERVER['HTTP_X_FORWARDED_PROTO'] ) { $_SERVER['HTTPS'] = 'on'; }\n\nif ( ! defined( 'ABSPATH' ) ) {\n\tdefine( 'ABSPATH', __DIR__ . '/' );\n}\nrequire_once ABSPATH . 'wp-settings.php';\n");
    s
}

fn db_ident(name: &str) -> String {
    let s: String = crate::util::slug(name).replace('-', "_").chars().take(40).collect();
    if s.is_empty() { "site".into() } else { s }
}

impl Engine {
    /// Programs a one-click app needs that are not installed yet.
    pub fn app_requirements(&self, kind: &str) -> CoreResult<Vec<MissingRuntime>> {
        let need: &[RuntimeId] = match kind {
            "wordpress" => &[RuntimeId::Php, RuntimeId::Caddy, RuntimeId::Mariadb],
            "laravel" => &[RuntimeId::Php, RuntimeId::Caddy, RuntimeId::Composer],
            _ => return Err(CoreError::InvalidConfig("unknown app".into())),
        };
        Ok(need
            .iter()
            .filter(|r| self.runtimes.resolve(**r, None).is_err())
            .map(|r| MissingRuntime { id: r.key().into(), label: r.label().into(), hint: None })
            .collect())
    }

    /// Run a command and copy its output into a log stream live.
    pub(crate) async fn run_streamed(&self, mut cmd: tokio::process::Command, log_id: &str, prefix: &str, timeout: Duration) -> CoreResult<()> {
        use tokio::io::AsyncBufReadExt;
        cmd.stdin(std::process::Stdio::null()).stdout(std::process::Stdio::piped()).stderr(std::process::Stdio::piped()).kill_on_drop(true);
        let mut child = cmd.spawn().map_err(|e| CoreError::RuntimeMissing(format!("{prefix}: {e}")))?;
        let tail = Arc::new(std::sync::Mutex::new(Vec::<String>::new()));
        let mut tasks = vec![];
        for (rd, keep) in [(child.stdout.take().map(|x| Box::new(x) as Box<dyn tokio::io::AsyncRead + Unpin + Send>), false), (child.stderr.take().map(|x| Box::new(x) as Box<dyn tokio::io::AsyncRead + Unpin + Send>), true)] {
            let Some(rd) = rd else { continue };
            let logs = Arc::clone(&self.logs);
            let id = log_id.to_string();
            let prefix = prefix.to_string();
            let tail = Arc::clone(&tail);
            tasks.push(tokio::spawn(async move {
                let mut l = tokio::io::BufReader::new(rd).lines();
                while let Ok(Some(line)) = l.next_line().await {
                    logs.system(&id, format!("{prefix}: {line}"));
                    if keep {
                        let mut v = tail.lock().unwrap();
                        v.push(line);
                        if v.len() > 6 {
                            v.remove(0);
                        }
                    }
                }
            }));
        }
        let status = tokio::time::timeout(timeout, child.wait()).await.map_err(|_| CoreError::Other(format!("{prefix} timed out")))??;
        for t in tasks {
            let _ = t.await;
        }
        if status.success() {
            Ok(())
        } else {
            Err(CoreError::Other(format!("{prefix} failed:\n{}", tail.lock().unwrap().join("\n"))))
        }
    }

    /// New WordPress site in an empty folder, ready to start.
    pub async fn create_wordpress(&self, folder: PathBuf, name: Option<String>) -> CoreResult<Project> {
        use sha1::Digest;
        check_target(&folder)?;
        let name = name.filter(|n| !n.trim().is_empty()).unwrap_or_else(|| folder.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_else(|| "WordPress".into()));
        let client = crate::health::http_client(Duration::from_secs(600));
        self.logs.system(APPS_LOG, tr!("WordPress: กำลังหาเวอร์ชันล่าสุด…", "WordPress: finding the latest version…"));
        let info: serde_json::Value = client.get("https://api.wordpress.org/core/version-check/1.7/").send().await?.error_for_status()?.json().await?;
        let version = info["offers"][0]["version"].as_str().unwrap_or("").to_string();
        if version.is_empty() || !version.chars().all(|c| c.is_ascii_digit() || c == '.') {
            return Err(CoreError::Network("unexpected WordPress version info".into()));
        }
        let url = format!("https://wordpress.org/wordpress-{version}.zip");
        let expected = client.get(format!("{url}.sha1")).send().await?.error_for_status()?.text().await?.split_whitespace().next().unwrap_or("").to_ascii_lowercase();
        if expected.len() != 40 || !expected.chars().all(|c| c.is_ascii_hexdigit()) {
            return Err(CoreError::Verification("WordPress checksum not available".into()));
        }
        self.logs.system(APPS_LOG, tr!("WordPress {}: กำลังดาวน์โหลด…", "WordPress {}: downloading…", version));
        let bytes = client.get(&url).send().await?.error_for_status()?.bytes().await?;
        let got = hex::encode(sha1::Sha1::digest(&bytes));
        if got != expected {
            return Err(CoreError::Verification(format!("WordPress checksum mismatch (expected {expected}, got {got})")));
        }
        let dl = self.paths.runtimes_dir.join("_downloads");
        std::fs::create_dir_all(&dl)?;
        let zip_path = dl.join(format!("wordpress-{version}.zip"));
        std::fs::write(&zip_path, &bytes)?;
        let staging = dl.join(format!("wp-{}", uuid::Uuid::new_v4().simple()));
        let res = (|| -> CoreResult<()> {
            crate::runtime::extract_zip(&zip_path, &staging)?;
            let src = staging.join("wordpress");
            if !src.join("wp-settings.php").is_file() {
                return Err(CoreError::Verification("unexpected WordPress archive layout".into()));
            }
            if let Some(parent) = folder.parent() {
                std::fs::create_dir_all(parent)?;
            }
            if folder.exists() {
                std::fs::remove_dir(&folder)?; // empty (checked above)
            }
            std::fs::rename(&src, &folder).or_else(|_| copy_dir(&src, &folder))?;
            Ok(())
        })();
        let _ = std::fs::remove_dir_all(&staging);
        let _ = std::fs::remove_file(&zip_path);
        res?;
        let db = format!("wp_{}", db_ident(&name));
        std::fs::write(folder.join("wp-config.php"), wp_config(&db))?;
        let p = Project {
            name,
            kind: ServerKind::PhpWebsite,
            folder: folder.clone(),
            port: self.projects.next_free_port(8001),
            protocol: Protocol::Http,
            health: HealthCheck::Http { path: "/wp-includes/images/blank.gif".into() },
            web_server: WebServerChoice::Caddy,
            database: DatabaseConfig { driver: DbDriver::Mariadb, name: db, ..Default::default() },
            template: Some("wordpress".into()),
            ..Default::default()
        };
        let p = self.projects.create(p)?;
        self.logs.system(APPS_LOG, tr!("WordPress {} พร้อมแล้ว: {}", "WordPress {} is ready: {}", version, folder.display()));
        Ok(p)
    }

    /// New Laravel app via `composer create-project`.
    pub async fn create_laravel(&self, folder: PathBuf, name: Option<String>) -> CoreResult<Project> {
        check_target(&folder)?;
        let name = name.filter(|n| !n.trim().is_empty()).unwrap_or_else(|| folder.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_else(|| "Laravel".into()));
        let php = self.runtimes.resolve(RuntimeId::Php, self.settings().runtime_versions.get("php").map(|s| s.as_str()))?;
        let phar = self.runtimes.resolve(RuntimeId::Composer, None)?;
        let parent = folder.parent().ok_or_else(|| CoreError::InvalidConfig("invalid folder".into()))?.to_path_buf();
        std::fs::create_dir_all(&parent)?;
        if folder.exists() {
            std::fs::remove_dir(&folder)?; // empty (checked above)
        }
        let dir_name = folder.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
        let home = self.paths.data_dir.join("composer");
        std::fs::create_dir_all(&home)?;
        let mut cmd = crate::util::hidden_tokio_command(&php);
        if let Some(ini) = self.runtimes.php_ini(&php) {
            cmd.arg("-c").arg(ini);
        }
        // the app's PHP first on PATH, so Laravel's own scripts (php artisan …) use it
        let path = format!("{};{}", php.parent().unwrap().display(), std::env::var("PATH").unwrap_or_default());
        cmd.arg(&phar)
            .args(["create-project", "laravel/laravel", &dir_name, "--prefer-dist", "--no-interaction", "--no-progress", "--no-ansi"])
            .current_dir(&parent)
            .env("COMPOSER_HOME", &home)
            .env("COMPOSER_NO_INTERACTION", "1")
            .env("PATH", path);
        self.logs.system(APPS_LOG, tr!("Laravel: กำลังสร้างโปรเจกต์ (1–3 นาที)…", "Laravel: creating the project (1–3 minutes)…"));
        self.run_streamed(cmd, APPS_LOG, "composer", Duration::from_secs(30 * 60)).await?;
        if !folder.join("artisan").is_file() {
            return Err(CoreError::Other(tr!("สร้าง Laravel ไม่สำเร็จ (ไม่พบไฟล์ artisan)", "Laravel was not created (artisan not found)")));
        }
        let sqlite = folder.join("database").join("database.sqlite");
        let has_sqlite = sqlite.is_file();
        let p = Project {
            name,
            kind: ServerKind::PhpWebsite,
            folder: folder.clone(),
            web_root: "public".into(),
            port: self.projects.next_free_port(8001),
            protocol: Protocol::Http,
            health: HealthCheck::Http { path: "/up".into() },
            web_server: WebServerChoice::Caddy,
            // Laravel keeps using its own .env (SQLite by default); the table editor can open it.
            database: if has_sqlite {
                DatabaseConfig { driver: DbDriver::Sqlite, name: "database".into(), sqlite_path: Some(sqlite), auto_setup: false, config_adapter: ConfigAdapter::None, ..Default::default() }
            } else {
                DatabaseConfig::default()
            },
            template: Some("laravel".into()),
            ..Default::default()
        };
        let p = self.projects.create(p)?;
        self.logs.system(APPS_LOG, tr!("Laravel พร้อมแล้ว: {}", "Laravel is ready: {}", folder.display()));
        Ok(p)
    }
}

fn copy_dir(src: &Path, dst: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dst)?;
    for e in std::fs::read_dir(src)? {
        let e = e?;
        let to = dst.join(e.file_name());
        if e.file_type()?.is_dir() {
            copy_dir(&e.path(), &to)?;
        } else {
            std::fs::copy(e.path(), to)?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn wp_config_has_no_password_and_valid_keys() {
        let c = wp_config("wp_myblog");
        assert!(c.contains("getenv( 'DB_PASSWORD' )"));
        assert!(c.contains("'wp_myblog'"));
        assert_eq!(c.matches("define( 'AUTH_KEY'").count(), 1);
        // keys never contain quotes or backslashes (would break PHP)
        for l in c.lines().filter(|l| l.contains("_KEY'") || l.contains("_SALT'")) {
            let v = l.split("', '").nth(1).unwrap();
            assert!(!v.trim_end_matches("' );").contains(['\'', '\\']));
        }
        assert_eq!(db_ident("My Blog!"), "my_blog");
    }
}
