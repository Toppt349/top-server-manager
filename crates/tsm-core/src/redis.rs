//! Local Redis (cache / queue / session store for Laravel, WordPress …).
//!
//! Runs only on 127.0.0.1, is never published, and keeps its data in the
//! app's data folder. Remembers whether the user turned it on, so it comes
//! back after a reboot.

use crate::engine::Engine;
use crate::error::{CoreError, CoreResult};
use crate::model::*;
use crate::runtime::RuntimeId;
use crate::tr;
use serde::Serialize;
use std::collections::BTreeMap;
use std::path::PathBuf;
use std::sync::Arc;
use std::time::Duration;
use tokio::io::{AsyncReadExt, AsyncWriteExt};

pub const REDIS_ID: &str = "__redis";
pub const REDIS_DEFAULT_PORT: u16 = 6379;
/// Upper bound so a runaway script cannot eat all the RAM of the computer.
const REDIS_MAX_MEMORY_MB: u32 = 512;

#[derive(Debug, Clone, Serialize)]
pub struct RedisStatus {
    pub installed: bool,
    pub version: Option<String>,
    pub running: bool,
    pub port: Option<u16>,
    /// Number of keys in database 0 (when running).
    pub keys: Option<u64>,
    /// e.g. "1.02M" (when running).
    pub memory: Option<String>,
    pub max_memory_mb: u32,
    /// Turned on by the user: started again with the app.
    pub autostart: bool,
}

/// redis.conf written before every start. Paths are relative to the working
/// directory (the Redis build uses an MSYS2 runtime, so Windows drive paths
/// are avoided entirely).
pub fn redis_conf(port: u16) -> String {
    format!(
        "# Generated by TOP Server Manager - rewritten every time Redis starts.\n\
         # This computer only: never bind to other addresses.\n\
         bind 127.0.0.1\n\
         port {port}\n\
         protected-mode yes\n\
         dir ./data\n\
         dbfilename dump.rdb\n\
         logfile \"\"\n\
         loglevel notice\n\
         databases 16\n\
         save 3600 1 300 100 60 10000\n\
         appendonly no\n\
         maxmemory {REDIS_MAX_MEMORY_MB}mb\n\
         maxmemory-policy noeviction\n\
         # CONFIG SET cannot move the data folder (blocks writing files elsewhere).\n\
         enable-protected-configs no\n\
         enable-debug-command no\n\
         enable-module-command no\n"
    )
}

/// One RESP reply, enough for PING / DBSIZE / INFO / SAVE.
#[derive(Debug, PartialEq)]
pub enum Reply {
    Simple(String),
    Error(String),
    Int(i64),
    Bulk(Option<String>),
    Array(Vec<Reply>),
}

pub fn encode_command(args: &[&str]) -> Vec<u8> {
    let mut out = format!("*{}\r\n", args.len()).into_bytes();
    for a in args {
        out.extend_from_slice(format!("${}\r\n", a.len()).as_bytes());
        out.extend_from_slice(a.as_bytes());
        out.extend_from_slice(b"\r\n");
    }
    out
}

/// Parse a complete reply from `buf`; `None` when more bytes are needed.
pub fn parse_reply(buf: &[u8]) -> Option<Reply> {
    parse_at(buf, 0).map(|(r, _)| r)
}

/// Reply starting at `pos` and the position right after it.
fn parse_at(buf: &[u8], pos: usize) -> Option<(Reply, usize)> {
    let rest = buf.get(pos..)?;
    let end = pos + rest.windows(2).position(|w| w == b"\r\n")?;
    let line = String::from_utf8_lossy(&buf[pos + 1..end]).to_string();
    let next = end + 2;
    match buf[pos] {
        b'+' => Some((Reply::Simple(line), next)),
        b'-' => Some((Reply::Error(line), next)),
        b':' => Some((Reply::Int(line.parse().ok()?), next)),
        b'$' => {
            let len: i64 = line.parse().ok()?;
            if len < 0 {
                return Some((Reply::Bulk(None), next));
            }
            let stop = next + len as usize;
            if buf.len() < stop + 2 {
                return None;
            }
            Some((Reply::Bulk(Some(String::from_utf8_lossy(&buf[next..stop]).to_string())), stop + 2))
        }
        b'*' => {
            let n: i64 = line.parse().ok()?;
            let mut items = vec![];
            let mut at = next;
            for _ in 0..n.max(0) {
                let (r, after) = parse_at(buf, at)?;
                items.push(r);
                at = after;
            }
            Some((Reply::Array(items), at))
        }
        _ => Some((Reply::Error("unexpected reply".into()), buf.len())),
    }
}

/// Send one command to the local Redis and read its reply.
pub async fn command(port: u16, args: &[&str]) -> CoreResult<Reply> {
    let fut = async {
        let mut s = tokio::net::TcpStream::connect(("127.0.0.1", port)).await?;
        s.write_all(&encode_command(args)).await?;
        let mut buf = Vec::new();
        let mut chunk = [0u8; 8192];
        loop {
            let n = s.read(&mut chunk).await?;
            if n == 0 {
                return Err(CoreError::Other("Redis closed the connection".into()));
            }
            buf.extend_from_slice(&chunk[..n]);
            if let Some(r) = parse_reply(&buf) {
                return Ok(r);
            }
            if buf.len() > 4 << 20 {
                return Err(CoreError::Other("Redis reply too large".into()));
            }
        }
    };
    tokio::time::timeout(Duration::from_secs(3), fut).await.map_err(|_| CoreError::Other("Redis did not answer".into()))?
}

pub async fn ping(port: u16) -> bool {
    matches!(command(port, &["PING"]).await, Ok(Reply::Simple(s)) if s == "PONG")
}

/// `used_memory_human:1.02M` → `1.02M`
pub fn info_field(info: &str, key: &str) -> Option<String> {
    info.lines().find_map(|l| l.strip_prefix(&format!("{key}:")).map(|v| v.trim().to_string()))
}

impl Engine {
    fn redis_dir(&self) -> PathBuf {
        self.paths.data_dir.join("redis")
    }

    fn redis_port_file(&self) -> PathBuf {
        self.redis_dir().join("port.txt")
    }

    fn redis_autostart_file(&self) -> PathBuf {
        self.redis_dir().join("autostart")
    }

    fn redis_saved_port(&self) -> Option<u16> {
        std::fs::read_to_string(self.redis_port_file()).ok()?.trim().parse().ok()
    }

    fn redis_project_at(&self, port: u16) -> Project {
        Project {
            id: REDIS_ID.into(),
            name: "Redis".into(),
            kind: ServerKind::CustomExecutable,
            folder: self.redis_dir(),
            port,
            protocol: Protocol::Tcp,
            bind: BindMode::Localhost,
            internal: true,
            auto_restart: true,
            health: HealthCheck::Tcp,
            ..Default::default()
        }
    }

    /// Internal project for re-attaching after an app restart.
    pub fn redis_project(&self) -> Option<Project> {
        Some(self.redis_project_at(self.redis_saved_port()?))
    }

    pub fn redis_autostart(&self) -> bool {
        self.redis_autostart_file().is_file()
    }

    pub async fn redis_status(&self) -> RedisStatus {
        let installed = self.runtimes.installed(RuntimeId::Redis);
        let port = self.redis_saved_port();
        let running = self.supervisor.is_active(REDIS_ID);
        let (mut keys, mut memory) = (None, None);
        if let (true, Some(p)) = (running, port) {
            if let Ok(Reply::Int(n)) = command(p, &["DBSIZE"]).await {
                keys = Some(n.max(0) as u64);
            }
            if let Ok(Reply::Bulk(Some(info))) = command(p, &["INFO", "memory"]).await {
                memory = info_field(&info, "used_memory_human");
            }
        }
        RedisStatus {
            installed: !installed.is_empty() || self.runtimes.resolve(RuntimeId::Redis, None).is_ok(),
            version: installed.first().map(|r| r.version.clone()),
            running,
            port,
            keys,
            memory,
            max_memory_mb: REDIS_MAX_MEMORY_MB,
            autostart: self.redis_autostart(),
        }
    }

    /// Start Redis on 127.0.0.1 (6379, or the next free port). Returns the port.
    pub async fn start_redis(self: &Arc<Self>) -> CoreResult<u16> {
        let exe = self
            .runtimes
            .resolve(RuntimeId::Redis, self.settings().runtime_versions.get("redis").map(|s| s.as_str()))
            .map_err(|_| CoreError::RuntimeMissing(tr!("ยังไม่ได้ติดตั้ง Redis", "Redis is not installed")))?;
        let dir = self.redis_dir();
        std::fs::create_dir_all(dir.join("data"))?;
        std::fs::write(self.redis_autostart_file(), b"1")?;
        if let (true, Some(port)) = (self.supervisor.is_active(REDIS_ID), self.redis_saved_port()) {
            return Ok(port);
        }
        let port = match self.redis_saved_port() {
            Some(p) if crate::ports::is_available(p, Protocol::Tcp) => p,
            _ if crate::ports::is_available(REDIS_DEFAULT_PORT, Protocol::Tcp) => REDIS_DEFAULT_PORT,
            _ => crate::ports::find_free_tcp(REDIS_DEFAULT_PORT + 1, &[]).ok_or_else(|| CoreError::Other("no free port for Redis".into()))?,
        };
        std::fs::write(self.redis_port_file(), port.to_string())?;
        std::fs::write(dir.join("redis.conf"), redis_conf(port))?;
        let project = self.redis_project_at(port);
        let spec = crate::process::UnitSpec {
            name: "redis-server".into(),
            program: exe,
            args: vec!["redis.conf".into()],
            cwd: dir,
            env: BTreeMap::new(),
            stdin: false,
            log_file: self.paths.project_log_file(REDIS_ID, "redis-server"),
        };
        self.supervisor.start_units(&project, vec![spec], vec![], self.spawn_options(&project)).await?;
        for _ in 0..40 {
            if ping(port).await {
                return Ok(port);
            }
            if !self.supervisor.is_active(REDIS_ID) {
                break;
            }
            tokio::time::sleep(Duration::from_millis(250)).await;
        }
        Err(CoreError::Other(tr!("Redis ไม่ตอบสนอง (ดูบันทึก __redis)", "Redis did not respond (see the __redis log)")))
    }

    /// Save the data to disk, then stop. Turning it off also means it no
    /// longer starts with the app.
    pub async fn stop_redis(&self) -> CoreResult<()> {
        let _ = std::fs::remove_file(self.redis_autostart_file());
        if let Some(port) = self.redis_saved_port() {
            if self.supervisor.is_active(REDIS_ID) {
                let _ = command(port, &["SAVE"]).await;
            }
        }
        self.supervisor.stop(REDIS_ID, false).await
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_is_local_only_and_safe() {
        let c = redis_conf(6380);
        assert!(c.contains("\nbind 127.0.0.1\n"));
        assert!(c.contains("\nport 6380\n"));
        assert!(c.contains("protected-mode yes"));
        assert!(c.contains("enable-protected-configs no"));
        assert!(c.contains("maxmemory 512mb"));
        assert!(!c.contains(":\\"), "no Windows drive paths in redis.conf");
        assert!(!c.contains("0.0.0.0"));
    }

    #[test]
    fn resp_round_trip() {
        assert_eq!(encode_command(&["SET", "k", "สวัสดี"]), b"*3\r\n$3\r\nSET\r\n$1\r\nk\r\n$18\r\n\xe0\xb8\xaa\xe0\xb8\xa7\xe0\xb8\xb1\xe0\xb8\xaa\xe0\xb8\x94\xe0\xb8\xb5\r\n".to_vec());
        assert_eq!(parse_reply(b"+PONG\r\n"), Some(Reply::Simple("PONG".into())));
        assert_eq!(parse_reply(b":42\r\n"), Some(Reply::Int(42)));
        assert_eq!(parse_reply(b"-ERR bad\r\n"), Some(Reply::Error("ERR bad".into())));
        assert_eq!(parse_reply(b"$-1\r\n"), Some(Reply::Bulk(None)));
        assert_eq!(parse_reply(b"$5\r\nhel"), None, "incomplete bulk waits for more bytes");
        assert_eq!(parse_reply(b"$5\r\nhello\r\n"), Some(Reply::Bulk(Some("hello".into()))));
        assert_eq!(parse_reply(b"+PO"), None);
        assert_eq!(
            parse_reply(b"*2\r\n$4\r\nbind\r\n$9\r\n127.0.0.1\r\n"),
            Some(Reply::Array(vec![Reply::Bulk(Some("bind".into())), Reply::Bulk(Some("127.0.0.1".into()))]))
        );
        assert_eq!(parse_reply(b"*2\r\n$4\r\nbind\r\n$9\r\n127"), None, "incomplete array waits");
        assert_eq!(parse_reply(b"*0\r\n"), Some(Reply::Array(vec![])));
        let info = "# Memory\r\nused_memory:1069328\r\nused_memory_human:1.02M\r\n";
        assert_eq!(info_field(info, "used_memory_human").as_deref(), Some("1.02M"));
        assert_eq!(info_field(info, "nope"), None);
    }
}
